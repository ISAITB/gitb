package com.gitb.tbs.rest;

import com.gitb.engine.CallbackAuthorizer;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.RestControllerAdvice;

@RestControllerAdvice
public class CallbackExceptionHandler {

    @ExceptionHandler(CallbackAuthorizer.CallbackAuthorizationException.class)
    public ResponseEntity<String> handleCallbackAuthorizationException(CallbackAuthorizer.CallbackAuthorizationException e) {
        return ResponseEntity.status(HttpStatus.FORBIDDEN).body("Callback request denied");
    }

}
